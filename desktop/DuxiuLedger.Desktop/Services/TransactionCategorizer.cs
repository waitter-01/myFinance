    public static string Suggest(TransactionRecord record)
    {
        if (!string.IsNullOrWhiteSpace(record.Category) && record.Category != "未分类") return record.Category;
        if (record.Direction == "转账") return "未分类";
        var text = $"{record.Merchant} {record.Note}";
        var rules = record.Direction == "收入" ? IncomeRules : ExpenseRules;
        foreach (var (category, keywords) in rules)
        {
            if (keywords.Any(keyword => text.Contains(keyword, StringComparison.OrdinalIgnoreCase))) return category;
        }
        return "未分类";
    }
